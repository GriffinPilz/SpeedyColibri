"""Reference vectors for the DeepSeek-V4 pieces implemented in dsv4.rs.

TRANSCRIBED from inference/kernel.py and inference/model.py, not re-derived from the
Rust — a re-derivation reproduces whatever misreading the Rust already contains. Where
the reference casts to a hardware float type, torch's own cast is used rather than a
hand-rolled rounding table, so the rounding is defined by the format and not by me.

Emits Rust literals for a #[test] in dsv4.rs.
"""
